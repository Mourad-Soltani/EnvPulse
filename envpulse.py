import argparse
import json
import os
import re
import sys
from pathlib import Path
from typing import Dict, List, Tuple

# Signature: Mourad.Soltani

SECRET_PATTERNS = [
    (r"AKIA[0-9A-Z]{16}", "AWS Access Key"),
    (r"ghp_[a-zA-Z0-9]{36}", "GitHub PAT"),
    (r"sk-[a-zA-Z0-9]{48}", "OpenAI Key"),
    (r"sk_live_[a-zA-Z0-9]{24}", "Stripe Live Key"),
    (r"-----BEGIN (RSA |EC |OPENSSH )?PRIVATE KEY-----", "Private Key"),
    (r"(api[_-]?key|secret|token|password)\s*=\s*['\"][^'\"]{8,}['\"]", "Generic Secret"),
]

def load_env(path: Path) -> Dict[str, str]:
    env = {}
    if not path.exists():
        return env
    for line in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        env[key.strip()] = value.strip().strip("'\"")
    return env

def scan_secrets(path: Path) -> List[dict]:
    findings = []
    if not path.exists():
        return findings
    content = path.read_text(encoding="utf-8", errors="ignore")
    for i, line in enumerate(content.splitlines(), 1):
        for pattern, name in SECRET_PATTERNS:
            if re.search(pattern, line, re.IGNORECASE):
                findings.append({
                    "file": str(path),
                    "line": i,
                    "type": name,
                    "snippet": line[:80] + ("..." if len(line) > 80 else "")
                })
    return findings

def diff_envs(example: Dict[str, str], actual: Dict[str, str]) -> dict:
    missing = sorted(set(example) - set(actual))
    extra = sorted(set(actual) - set(example))
    return {"missing": missing, "extra": extra}

def generate_example(env: Dict[str, str]) -> str:
    lines = ["# Generated by EnvPulse — Built by Mourad.Soltani", ""]
    for key in sorted(env):
        lines.append(f"{key}=")
    return "\n".join(lines) + "\n"

def main():
    parser = argparse.ArgumentParser(description="EnvPulse by Mourad.Soltani")
    sub = parser.add_subparsers(dest="cmd", required=True)

    p_scan = sub.add_parser("scan", help="Scan .env files for secrets")
    p_scan.add_argument("--path", default=".", help="Directory to scan")
    p_scan.add_argument("--json", action="store_true")

    p_diff = sub.add_parser("diff", help="Compare .env vs .env.example")
    p_diff.add_argument("--env", default=".env")
    p_diff.add_argument("--example", default=".env.example")
    p_diff.add_argument("--json", action="store_true")

    p_gen = sub.add_parser("generate", help="Generate redacted .env.example")
    p_gen.add_argument("--env", default=".env")
    p_gen.add_argument("--out", default=".env.example")

    args = parser.parse_args()

    if args.cmd == "scan":
        root = Path(args.path)
        findings = []
        for p in root.rglob(".env*"):
            if p.is_file() and not p.name.endswith(".example"):
                findings.extend(scan_secrets(p))
        if args.json:
            print(json.dumps({"findings": findings, "count": len(findings)}, indent=2))
        else:
            if not findings:
                print("No secrets detected.")
            else:
                for f in findings:
                    print(f"[{f['type']}] {f['file']}:{f['line']} — {f['snippet']}")
                print(f"\n{len(findings)} potential secret(s) found.")
        sys.exit(1 if findings else 0)

    elif args.cmd == "diff":
        ex = load_env(Path(args.example))
        act = load_env(Path(args.env))
        result = diff_envs(ex, act)
        if args.json:
            print(json.dumps(result, indent=2))
        else:
            if result["missing"]:
                print("Missing in .env:", ", ".join(result["missing"]))
            if result["extra"]:
                print("Extra in .env:", ", ".join(result["extra"]))
            if not result["missing"] and not result["extra"]:
                print("Env files are in sync.")
        sys.exit(1 if result["missing"] else 0)

    elif args.cmd == "generate":
        env = load_env(Path(args.env))
        content = generate_example(env)
        Path(args.out).write_text(content, encoding="utf-8")
        print(f"Wrote {args.out} ({len(env)} keys, values redacted).")

if __name__ == "__main__":
    main()
